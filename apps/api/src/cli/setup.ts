import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import pg from "pg";

/**
 * One-time LOCAL database setup, for development with docker-compose. It does what an operator does in production,
 * with generated credentials: create the roles (sql/bootstrap-roles.sql), give them random passwords, create the
 * database owned by the migrator, harden it (sql/harden-database.sql), and write the connection settings to the
 * git-ignored apps/api/.env. Passwords and the credential pepper are random per run and are never printed.
 *
 *   pnpm --filter @agentaxio/api db:setup
 *
 * It refuses to overwrite an existing .env (that would orphan the old passwords) unless run with --force, and refuses
 * any database name that is not an obvious development name.
 */

const API_DIR = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const DATABASE_NAME = /^[a-z][a-z0-9_]{2,40}_dev$/;

export interface LocalSetupResult {
  env: Record<string, string>;
}

export async function setupLocalDatabase(
  adminUrl: string,
  database: string,
): Promise<LocalSetupResult> {
  if (!DATABASE_NAME.test(database)) {
    throw new Error(
      "the database name must be lowercase letters, digits and underscores, ending in _dev",
    );
  }
  const passwords = {
    migrator: randomBytes(18).toString("hex"),
    agentApi: randomBytes(18).toString("hex"),
    management: randomBytes(18).toString("hex"),
    executor: randomBytes(18).toString("hex"),
  };

  const admin = new pg.Client({ connectionString: adminUrl });
  await admin.connect();
  try {
    await admin.query(readFileSync(join(API_DIR, "sql", "bootstrap-roles.sql"), "utf8"));
    // Passwords are hex, so inlining them is safe; ALTER ROLE does not accept bind parameters.
    await admin.query(`ALTER ROLE axo_migrator LOGIN PASSWORD '${passwords.migrator}'`);
    await admin.query(`ALTER ROLE axo_agent_api LOGIN PASSWORD '${passwords.agentApi}'`);
    await admin.query(`ALTER ROLE axo_management LOGIN PASSWORD '${passwords.management}'`);
    await admin.query(`ALTER ROLE axo_executor LOGIN PASSWORD '${passwords.executor}'`);
    const exists = await admin.query("SELECT 1 FROM pg_database WHERE datname = $1", [database]);
    if (exists.rowCount === 0) await admin.query(`CREATE DATABASE ${database} OWNER axo_migrator`);
  } finally {
    await admin.end();
  }

  const target = new URL(adminUrl);
  target.pathname = `/${database}`;
  const hardener = new pg.Client({ connectionString: target.toString() });
  await hardener.connect();
  try {
    await hardener.query(readFileSync(join(API_DIR, "sql", "harden-database.sql"), "utf8"));
  } finally {
    await hardener.end();
  }

  const url = (user: string, password: string) => {
    const u = new URL(adminUrl);
    u.pathname = `/${database}`;
    u.username = user;
    u.password = password;
    return u.toString();
  };
  return {
    env: {
      AXO_MIGRATOR_DATABASE_URL: url("axo_migrator", passwords.migrator),
      AXO_AGENT_API_DATABASE_URL: url("axo_agent_api", passwords.agentApi),
      AXO_MANAGEMENT_DATABASE_URL: url("axo_management", passwords.management),
      AXO_EXECUTOR_DATABASE_URL: url("axo_executor", passwords.executor),
      AXO_CREDENTIAL_PEPPER: randomBytes(32).toString("base64url"),
      // Local development keys. A real deployment takes these from a key-management service (docs/BE-02-DECISIONS.md D9).
      AXO_DATA_KEYS: JSON.stringify({ k1: randomBytes(32).toString("base64url") }),
      AXO_DATA_KEY_ID: "k1",
      // Held by the executor only; the mock CRM must be started with the same value.
      AXO_MOCK_CRM_TOKEN: randomBytes(32).toString("base64url"),
    },
  };
}

async function main(): Promise<void> {
  const envFile = join(API_DIR, ".env");
  if (existsSync(envFile) && !process.argv.includes("--force")) {
    throw new Error(
      "apps/api/.env already exists; pass --force to replace it (this rotates all database passwords)",
    );
  }
  const password = process.env.POSTGRES_PASSWORD;
  if (password === undefined || password === "") {
    throw new Error(
      "POSTGRES_PASSWORD is not set; copy .env.example to .env at the repository root first",
    );
  }
  const adminUrl =
    process.env.AXO_ADMIN_DATABASE_URL ??
    `postgres://${process.env.POSTGRES_USER ?? "axo_admin"}:${encodeURIComponent(password)}@127.0.0.1:5432/postgres`;
  const database = process.env.POSTGRES_DB ?? "agentaxio_dev";
  const { env } = await setupLocalDatabase(adminUrl, database);
  writeFileSync(
    envFile,
    `# Generated by db:setup. Local development only. Git-ignored. Never commit or share.\n${Object.entries(
      env,
    )
      .map(([k, v]) => `${k}=${v.startsWith("{") ? `'${v}'` : v}`)
      .join("\n")}\n`,
    { mode: 0o600 },
  );
  process.stdout.write(`Wrote ${envFile}. Next: pnpm --filter @agentaxio/api db:migrate\n`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error: unknown) => {
    process.stderr.write(
      `db:setup failed: ${error instanceof Error ? error.message : "unknown error"}\n`,
    );
    process.exitCode = 1;
  });
}
